CREATE TABLE IF NOT EXISTS match_commands (
    event_id UUID PRIMARY KEY,
    topic VARCHAR(255) NOT NULL,
    order_id BIGINT NOT NULL,
    delivery_id BIGINT NOT NULL,
    payload TEXT NOT NULL,
    payload_fingerprint VARCHAR(64) NOT NULL,
    candidate_payload TEXT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP NULL,
    CONSTRAINT ck_match_commands_status
        CHECK (status IN ('PENDING', 'CANDIDATE_STAGED', 'RESULT_STAGED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_match_commands_delivery
    ON match_commands (delivery_id, status);
CREATE INDEX IF NOT EXISTS idx_match_commands_order
    ON match_commands (order_id, created_at);

CREATE TABLE IF NOT EXISTS match_outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL,
    command_event_id UUID NOT NULL,
    aggregate_id VARCHAR(255) NOT NULL,
    event_type VARCHAR(128) NOT NULL,
    topic VARCHAR(255) NOT NULL,
    event_key VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    traceparent VARCHAR(55) NULL,
    status VARCHAR(16) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    sent_at TIMESTAMP NULL,
    last_error VARCHAR(2000) NULL,
    CONSTRAINT uk_match_outbox_event_id UNIQUE (event_id),
    CONSTRAINT ck_match_outbox_status CHECK (status IN ('PENDING', 'SENT', 'DEAD', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_match_outbox_pending
    ON match_outbox_events (status, next_attempt_at, created_at);
CREATE INDEX IF NOT EXISTS idx_match_outbox_command
    ON match_outbox_events (command_event_id);
CREATE INDEX IF NOT EXISTS idx_match_outbox_aggregate
    ON match_outbox_events (aggregate_id, created_at);
